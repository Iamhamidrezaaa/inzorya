function isFaToken(raw: string): boolean {
  const v = raw.toLowerCase().trim();
  return (
    v === "fa" ||
    v === "fa-ir" ||
    v.startsWith("fa-") ||
    v === "persian" ||
    v === "farsi" ||
    v.includes("فارسی")
  );
}

/** Detect UI/output language from AI task message payload. */
export function detectOutputLang(joined: string): "fa" | "en" {
  // Prefer the Input: block so Context (e.g. calendar language:en) cannot win.
  const inputIdx = joined.indexOf("Input:");
  const contextIdx = joined.indexOf("\nContext:");
  const haystack =
    inputIdx >= 0 && contextIdx > inputIdx
      ? joined.slice(inputIdx, contextIdx)
      : joined;

  if (/Respond entirely in Persian|Language rule:.*Persian|فارسی/i.test(joined)) {
    return "fa";
  }

  const m = haystack.match(/"language"\s*:\s*"([^"]+)"/i);
  if (m?.[1] && isFaToken(m[1])) return "fa";

  const loc = haystack.match(/"locale"\s*:\s*"([^"]+)"/i);
  if (loc?.[1] && isFaToken(loc[1])) return "fa";

  return "en";
}

